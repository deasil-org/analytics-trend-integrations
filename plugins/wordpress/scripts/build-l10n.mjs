// Writes the plugin's translations as the PHP files WordPress 6.5 and later
// load in place of .mo files, from i18n/<locale>.json (English → translation).
// No gettext tools are needed, and the catalogs stay plain JSON to review.
//
//   node scripts/build-l10n.mjs
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(import.meta.dirname, "..");
const PLUGIN = path.join(ROOT, "analyticstrend");

export const LOCALES = ["fr_FR", "es_ES", "pt_BR", "de_DE"];

const PLURAL_FORMS = {
  fr_FR: "nplurals=2; plural=n > 1;",
  pt_BR: "nplurals=2; plural=n > 1;",
  es_ES: "nplurals=2; plural=n != 1;",
  de_DE: "nplurals=2; plural=n != 1;",
};

function phpFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return entry.name === "languages" || entry.name === "assets" ? [] : phpFiles(full);
    return entry.name.endsWith(".php") ? [full] : [];
  });
}

/** Every string the plugin's PHP translates, in the order it first appears, with the header's description. */
export function msgids() {
  const ids = [];
  const add = (id) => ids.includes(id) || ids.push(id);
  for (const file of phpFiles(PLUGIN).sort()) {
    const php = readFileSync(file, "utf8");
    if (file.endsWith("analyticstrend.php")) add(php.match(/^ \* Description:\s+(.+)$/m)[1].trim());
    for (const [, raw] of php.matchAll(/\b(?:__|_e|esc_html__|esc_html_e|esc_attr__|esc_attr_e)\(\s*'((?:[^'\\]|\\.)*)'/g)) {
      add(raw.replace(/\\(['\\])/g, "$1"));
    }
  }
  return ids;
}

const phpString = (text) => `'${text.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;

export function l10nPhp(locale, messages) {
  const entries = Object.entries(messages).map(([id, text]) => `\t\t${phpString(id)} => ${phpString(text)},`);
  return [
    "<?php",
    "// Generated by scripts/build-l10n.mjs from i18n/" + locale + ".json. Do not edit.",
    "return array(",
    `\t'domain' => 'analyticstrend',`,
    `\t'language' => ${phpString(locale)},`,
    `\t'plural-forms' => ${phpString(PLURAL_FORMS[locale])},`,
    "\t'messages' => array(",
    ...entries,
    "\t),",
    ");",
    "",
  ].join("\n");
}

export function buildL10n() {
  const out = path.join(PLUGIN, "languages");
  mkdirSync(out, { recursive: true });
  for (const locale of LOCALES) {
    const messages = JSON.parse(readFileSync(path.join(ROOT, "i18n", `${locale}.json`), "utf8"));
    writeFileSync(path.join(out, `analyticstrend-${locale}.l10n.php`), l10nPhp(locale, messages));
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) buildL10n();
